begin;
create function pg_temp.assert_true(value boolean,label text) returns void language plpgsql as $$ begin
  if value is distinct from true then raise exception 'Falhou: %',label; end if;
end; $$;
create function pg_temp.denied(statement text,expected text) returns void language plpgsql as $$ begin
  begin execute statement; exception when others then if sqlstate=expected then return; end if; raise; end;
  raise exception 'Operação indevidamente aceita';
end; $$;
insert into auth.users(id,email) values('40000000-0000-4000-8000-000000000001','codes-sql@example.test');
insert into cali_workspace.profiles(id,role,active) values('40000000-0000-4000-8000-000000000001','admin',true);
set local role anon;
select pg_temp.denied('select cali_workspace.issue_workspace_code(''codes-sql@example.test'',repeat(''a'',64))','42501');
reset role;
set local role authenticated;
select pg_temp.denied('select cali_workspace.consume_workspace_code(''codes-sql@example.test'',repeat(''a'',64))','42501');
select pg_temp.denied('select * from cali_private.workspace_access_codes','42501');
reset role;
set local role service_role;
select cali_workspace.issue_workspace_code('codes-sql@example.test',repeat('a',64));
select pg_temp.assert_true(cali_workspace.consume_workspace_code('codes-sql@example.test',repeat('a',64)) is null,'pending não autentica');
reset role;
select cali_workspace.deliver_workspace_code(id,false) from cali_private.workspace_access_codes where email='codes-sql@example.test';
set local role service_role;
select pg_temp.assert_true(cali_workspace.consume_workspace_code('codes-sql@example.test',repeat('a',64)) is null,'falha de entrega invalida código');
reset role;
insert into cali_workspace.legal_versions(version,title,content) values('local-sql-immutable','Teste sintético','Conteúdo sintético imutável.');
select pg_temp.denied('update cali_workspace.legal_versions set content=''mudou'' where version=''local-sql-immutable''','55000');
select pg_temp.denied('delete from cali_workspace.legal_versions where version=''local-sql-immutable''','55000');
select pg_temp.assert_true((select length(content_hash)=64 from cali_workspace.legal_versions where version='local-sql-immutable'),'digest de conteúdo vem do servidor');
insert into cali_private.current_legal_version(singleton,version) values(true,'local-sql-immutable') on conflict(singleton) do update set version=excluded.version;
select pg_temp.assert_true(cali_workspace.get_current_terms()->>'version'='local-sql-immutable','conteúdo público corrente');
delete from cali_private.current_legal_version;
select pg_temp.assert_true(cali_workspace.get_current_terms() is null,'ausência de publicação não inventa versão');
set local role authenticated;
set local request.jwt.claims='{"sub":"40000000-0000-4000-8000-000000000001","aal":"aal2"}';
select pg_temp.assert_true(cali_workspace.workspace_access_state()->>'status'='signed_out','JWT sem sessão vigente não libera');
reset role;
rollback;
select 'Códigos/termos: SQL de grants, entrega e imutabilidade passou; fixtures revertidas.' as result;
